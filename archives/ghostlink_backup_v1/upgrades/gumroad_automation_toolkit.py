class ProductPackager:
    """Automated product packaging and versioning"""
    
    def __init__(self, output_dir="products"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(exist_ok=True)
        
    def create_package(self, tier, source_dir, version=None):
        """Create product package"""
        if version is None:
            version = datetime.now().strftime("%Y.%m.%d")
        
        filename = f"ghostlink_{tier}_{version}.zip"
        output_path = self.output_dir / filename
        
        print(f"[PACKAGE] Creating {filename}...")
        
        with zipfile.ZipFile(output_path, 'w', zipfile.ZIP_DEFLATED) as zipf:
            # Add all files from source directory
            for root, dirs, files in os.walk(source_dir):
                for file in files:
                    file_path = Path(root) / file
                    arcname = file_path.relative_to(source_dir)
                    zipf.write(file_path, arcname)
            
            # Add manifest
            manifest = self._generate_manifest(tier, version)
            zipf.writestr("MANIFEST.json", json.dumps(manifest, indent=2))
            
            # Add license
            license_key = self._generate_license()
            zipf.writestr("LICENSE.txt", license_key)
        
        # Generate hash
        file_hash = self._hash_file(output_path)
        
        print(f"[PACKAGE] Created: {output_path}")
        print(f"[PACKAGE] Hash: {file_hash}")
        
        return {
            "path": str(output_path),
            "hash": file_hash,
            "version": version,
            "tier": tier
        }
    
    def _generate_manifest(self, tier, version):
        """Generate package manifest"""
        return {
            "product": f"GHOSTLINK {tier.upper()}",
            "version": version,
            "created": datetime.now().isoformat(),
            "tier": tier,
            "schema": "ghostlink.kernel.v1.max"
        }
    
    def _generate_license(self):
        """Generate license text"""
        return f"""
GHOSTLINK LICENSE
Generated: {datetime.now().isoformat()}
License ID: {uuid.uuid4()}

This software is licensed for use according to the terms
of your Gumroad purchase. Unauthorized distribution is prohibited.
        """.strip()
    
    def _hash_file(self, filepath):
        """Generate SHA256 hash of file"""
        sha256 = hashlib.sha256()
        with open(filepath, 'rb') as f:
            for block in iter(lambda: f.read(4096), b''):
                sha256.update(block)
        return sha256.hexdigest()

