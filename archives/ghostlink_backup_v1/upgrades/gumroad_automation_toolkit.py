class RevenueTracker:
    """Track and analyze revenue"""
    
    def __init__(self, api):
        self.api = api
        
    def get_daily_revenue(self, date=None):
        """Get revenue for specific date"""
        if date is None:
            date = datetime.now().strftime("%Y-%m-%d")
        
        sales = self.api.get_sales(after=date, before=date)
        total = sum(sale["price"] for sale in sales.get("sales", []))
        
        return {
            "date": date,
            "revenue": total / 100,  # Convert cents to dollars
            "sales_count": len(sales.get("sales", [])),
            "sales": sales.get("sales", [])
        }
    
    def get_monthly_revenue(self, year, month):
        """Get revenue for specific month"""
        start = f"{year}-{month:02d}-01"
        # Calculate last day of month
        if month == 12:
            end = f"{year+1}-01-01"
        else:
            end = f"{year}-{month+1:02d}-01"
        
        sales = self.api.get_sales(after=start, before=end)
        total = sum(sale["price"] for sale in sales.get("sales", []))
        
        return {
            "period": f"{year}-{month:02d}",
            "revenue": total / 100,
            "sales_count": len(sales.get("sales", [])),
            "by_product": self._sales_by_product(sales.get("sales", []))
        }
    
    def _sales_by_product(self, sales):
        """Group sales by product"""
        by_product = {}
        for sale in sales:
            product_name = sale.get("product_name", "Unknown")
            if product_name not in by_product:
                by_product[product_name] = {
                    "count": 0,
                    "revenue": 0
                }
            by_product[product_name]["count"] += 1
            by_product[product_name]["revenue"] += sale["price"] / 100
        return by_product

