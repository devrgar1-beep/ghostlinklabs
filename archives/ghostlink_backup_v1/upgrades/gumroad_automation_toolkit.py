class GumroadAPI:
    """Complete Gumroad API wrapper"""
    
    def __init__(self, token=None):
        self.token = token or GumroadConfig.API_TOKEN
        self.base_url = GumroadConfig.API_BASE
        
    def _request(self, method, endpoint, **kwargs):
        """Make authenticated API request"""
        url = f"{self.base_url}{endpoint}"
        
        # Add token to data/params
        if method.upper() in ["POST", "PUT"]:
            if "data" not in kwargs:
                kwargs["data"] = {}
            kwargs["data"]["access_token"] = self.token
        else:
            if "params" not in kwargs:
                kwargs["params"] = {}
            kwargs["params"]["access_token"] = self.token
        
        response = requests.request(method, url, **kwargs)
        response.raise_for_status()
        return response.json()
    
    # Product Management
    def create_product(self, name, price, description, **kwargs):
        """Create new product"""
        data = {
            "name": name,
            "price": price / 100,  # Convert cents to dollars
            "description": description,
            "published": kwargs.get("published", False),
            **kwargs
        }
        return self._request("POST", "/products", data=data)
    
    def get_product(self, product_id):
        """Get product details"""
        return self._request("GET", f"/products/{product_id}")
    
    def update_product(self, product_id, **updates):
        """Update existing product"""
        return self._request("PUT", f"/products/{product_id}", data=updates)
    
    def delete_product(self, product_id):
        """Delete product"""
        return self._request("DELETE", f"/products/{product_id}")
    
    def list_products(self):
        """List all products"""
        return self._request("GET", "/products")
    
    # Sales & Customers
    def get_sales(self, after=None, before=None, page=1):
        """Get sales data"""
        params = {"page": page}
        if after:
            params["after"] = after
        if before:
            params["before"] = before
        return self._request("GET", "/sales", params=params)
    
    def get_subscribers(self, product_id):
        """Get product subscribers"""
        return self._request("GET", f"/products/{product_id}/subscribers")
    
    # License Keys
    def generate_license_key(self, product_id, email):
        """Generate license key for customer"""
        data = {
            "product_id": product_id,
            "email": email
        }
        return self._request("POST", "/licenses", data=data)
    
    def verify_license(self, product_id, license_key):
        """Verify license key"""
        data = {
            "product_id": product_id,
            "license_key": license_key
        }
        return self._request("POST", "/licenses/verify", data=data)

